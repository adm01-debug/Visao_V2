export const isString = (value: unknown): value is string => typeof value === 'string';
export const isNumber = (value: unknown): value is number => typeof value === 'number' && !isNaN(value);
export const isBoolean = (value: unknown): value is boolean => typeof value === 'boolean';
export const isObject = (value: unknown): value is Record<string, unknown> => typeof value === 'object' && value !== null && !Array.isArray(value);
export const isArray = <T>(value: unknown): value is T[] => Array.isArray(value);
export const isNull = (value: unknown): value is null => value === null;
export const isUndefined = (value: unknown): value is undefined => value === undefined;
export const isNullish = (value: unknown): value is null | undefined => value === null || value === undefined;
export const isDefined = <T>(value: T | null | undefined): value is T => value !== null && value !== undefined;
export const isFunction = (value: unknown): value is Function => typeof value === 'function';
export const isDate = (value: unknown): value is Date => value instanceof Date && !isNaN(value.getTime());
export const isError = (value: unknown): value is Error => value instanceof Error;
export const hasProperty = <K extends string>(obj: unknown, key: K): obj is Record<K, unknown> => isObject(obj) && key in obj;
